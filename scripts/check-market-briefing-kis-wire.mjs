import assert from 'node:assert/strict';
import wire from '../src/web/domain/market/market_briefing_kis_wire.js';
const registry={H0MFCNT0:{schemaId:'kis-h0mfcnt0-probe-v1',fieldCount:4}};
const good=wire.validateFrame('0|H0MFCNT0|1|101^102^103^104',registry);
assert.equal(good.status,'VALID');
assert.equal(good.fieldCount,4);
const mismatch=wire.validateFrame('0|H0MFCNT0|1|101^102^103',registry);
assert.equal(mismatch.status,'QUARANTINED');
assert.equal(mismatch.error,'FIELD_COUNT_MISMATCH');
const unknown=wire.validateFrame('0|H0STCNT0|1|a^b^c',registry);
assert.equal(unknown.status,'QUARANTINED');
assert.equal(unknown.error,'UNKNOWN_SCHEMA');
const malformed=wire.validateFrame('broken',registry);
assert.equal(malformed.status,'QUARANTINED');
const capture=wire.captureEnvelope('0|H0MFCNT0|1|101^102^103^104','2026-09-18T05:59:59+09:00',registry);
assert.equal(capture.rawFrame,'0|H0MFCNT0|1|101^102^103^104');
assert.equal(capture.receivedAt,'2026-09-18T05:59:59+09:00');
assert.equal(capture.schemaId,'kis-h0mfcnt0-probe-v1');
const probe=wire.sessionBoundaryProbe('K200',[{raw:'0|H0MFCNT0|1|101^102^103^104',receivedAt:'2026-09-18T05:59:59+09:00'}],registry);
assert.equal(probe.length,1);
assert.equal(probe[0].status,'VALID');
console.log('KIS 야간선물 raw-frame 보존/스키마 quarantine 회귀검사 통과');
