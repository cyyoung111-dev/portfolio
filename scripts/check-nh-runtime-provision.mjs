import assert from 'node:assert/strict';
import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import {makePublicBundle,sealCredentials,openCredentials,readRunArtifact} from './provision-nh-runtime.mjs';
const context={repository:'cyyoung111-dev/portfolio',runId:'123456789',attempt:'1',sha:'a'.repeat(40)};
const pair=makePublicBundle(context),credentials={key:'dummy-NH-key',secret:'dummy-NH-secret'};
assert.doesNotMatch(JSON.stringify(pair.publicBundle),/PRIVATE KEY|dummy-NH/);
assert.match(pair.privateKey,/PRIVATE KEY/);
const sealed=sealCredentials(pair.publicBundle,context,credentials);
assert.doesNotMatch(JSON.stringify(sealed),/dummy-NH-key|dummy-NH-secret|PRIVATE KEY/);
assert.deepEqual(openCredentials(sealed,context,pair.privateKey),credentials);
assert.throws(()=>openCredentials(sealed,{...context,runId:'987654321'},pair.privateKey),/CONTEXT_MISMATCH/);
assert.throws(()=>openCredentials({...sealed,sha:'b'.repeat(40)},context,pair.privateKey),/CONTEXT_MISMATCH/);
assert.throws(()=>openCredentials({...sealed,tag:'AAAA'},context,pair.privateKey),/DECRYPT_FAILED/);
assert.throws(()=>openCredentials(sealed,context,makePublicBundle(context).privateKey),/DECRYPT_FAILED/);
assert.throws(()=>makePublicBundle({...context,attempt:'2'}),/CONTEXT_INVALID/);
assert.throws(()=>sealCredentials({...pair.publicBundle,runId:'987654321'},context,credentials),/INPUT_INVALID/);
const long={key:'k'.repeat(2048),secret:'s'.repeat(2048)};
assert.deepEqual(openCredentials(sealCredentials(pair.publicBundle,context,long),context,pair.privateKey),long);
const zip=execFileSync('python3',['-c',"import io,zipfile,sys; b=io.BytesIO(); z=zipfile.ZipFile(b,'w',zipfile.ZIP_DEFLATED); z.writestr('public.json',sys.stdin.read()); z.close(); sys.stdout.buffer.write(b.getvalue())"],{input:JSON.stringify(pair.publicBundle)});
let artifactRequests=0;
const loaded=await readRunArtifact('nh-public-'+context.runId+'-1','public.json',context,{token:'dummy',request:async(url,options)=>{
  artifactRequests++;assert.equal(options.headers.authorization,'Bearer dummy');
  if(artifactRequests===1){assert.match(url,new RegExp('/actions/runs/'+context.runId+'/artifacts'));return {ok:true,json:async()=>({total_count:1,artifacts:[{id:42,name:'nh-public-'+context.runId+'-1',size_in_bytes:zip.length,expired:false}]})};}
  assert.match(url,/artifacts\/42\/zip$/);return {ok:true,arrayBuffer:async()=>zip};
}});
assert.deepEqual(loaded,pair.publicBundle);assert.equal(artifactRequests,2);
let count=0,now=0;
await assert.rejects(readRunArtifact('nh-public-'+context.runId+'-1','public.json',context,{token:'dummy',now:()=>now,wait:async()=>{now=180001;},request:async()=>{count++;return {ok:true,json:async()=>({total_count:0,artifacts:[]})};}}),/ARTIFACT_TIMEOUT/);
assert.equal(count,1);
await assert.rejects(readRunArtifact('nh-public-'+context.runId+'-1','public.json',context,{token:'dummy',request:async()=>({ok:true,json:async()=>({total_count:2,artifacts:[{name:'nh-public-'+context.runId+'-1'},{name:'nh-public-'+context.runId+'-1'}]})})}),/ARTIFACT_INVALID/);
await assert.rejects(readRunArtifact('nh-public-'+context.runId+'-1','public.json',context,{token:'dummy',request:async()=>{throw Error('private-response');}}),/^Error: NH_PROVISION_ARTIFACT_INVALID$/);
const workflow=fs.readFileSync('.github/workflows/provision-nh-runtime.yml','utf8');
assert.match(workflow,/production:[\s\S]*environment: portfolio-production-gas/);
assert.match(workflow,/seal:[\s\S]*environment: portfolio-market-data/);
assert.equal((workflow.match(/github\.ref == 'refs\/heads\/main' && github\.run_attempt == 1/g)||[]).length,2);
assert.match(workflow,/path: \.nh-runtime-provision\/public\.json/);
assert.match(workflow,/path: \.nh-runtime-provision\/envelope\.json/);
assert.doesNotMatch(workflow,/path:.*(?:private|\*|\.nh-runtime-provision\s*$)/m);
assert.match(workflow,/if: always\(\)[\s\S]*rm -f \.nh-runtime-provision\/private\.pem/);
console.log('NH provisioning: sealed credentials, context binding, tamper/replay rejection, bounded artifact wait and private-key isolation passed');
