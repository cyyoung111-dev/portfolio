const chart={meta:{symbol:'^KS11',exchangeTimezoneName:'Asia/Seoul',currentTradingPeriod:{regular:{end:Date.parse(date+'T15:30:00+09:00')/1000}}},timestamp:[Date.parse('2026-10-29T09:00:00+09:00')/1000,Date.parse(date+'T09:00:00+09:00')/1000],indicators:{quote:[{close:[100,101]}]}};
const fetchImpl=async()=>({ok:true,json:async()=>({chart:{result:[chart]}})});
const row=await fetchClosingIndex('KOSPI','^KS11',date,{fetchImpl,now:now()});
