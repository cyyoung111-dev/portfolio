assert.equal(payload.ready,true);assert.equal(fetched,2);
assert.match(payload.message,/2026-10-30/);assert.match(payload.message,/2026-10-29/);assert.match(payload.message,/Yahoo Finance/);
assert.equal((await deliverClose(payload,{now,send:async()=>{sent++;}})).status,'SENT');assert.equal(sent,1);
await assert.rejects(deliverClose(payload,{now,attempt:2,send:async()=>{sent++;}}),/PAYLOAD_INVALID/);
await assert.rejects(deliverClose({...payload,date:'2026-10-29'},{now,send:async()=>{sent++;}}),/PAYLOAD_INVALID/);
await assert.rejects(deliverClose(payload,{now:()=>new Date(date+'T17:10:00+09:00'),send:async()=>{sent++;}}),/PAYLOAD_INVALID/);
assert.equal(sent,1);
fetched=0;
const claimed=await prepareClose({...options,fetchImpl:async()=>({ok:true,json:async()=>({total_count:1,artifacts:[{name:'telegram-close-claim-'+date}]})})});
