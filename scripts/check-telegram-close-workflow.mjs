assert.equal(await fetchClosingIndex('KOSPI','^KS11',date,{fetchImpl,now:new Date(date+'T15:29:00+09:00')}),null);
chart.meta.currentTradingPeriod.regular.end=Date.parse('2026-10-29T15:30:00+09:00')/1000;
assert.equal(await fetchClosingIndex('KOSPI','^KS11',date,{fetchImpl,now:now()}),null);
chart.meta.currentTradingPeriod.regular.end=Date.parse(date+'T15:30:00+09:00')/1000;
chart.timestamp.push(chart.timestamp[1]);chart.indicators.quote[0].close.push(102);
assert.equal(await fetchClosingIndex('KOSPI','^KS11',date,{fetchImpl,now:now()}),null);
let fetched=0,sent=0;
const options={now,githubToken:'dummy',repository:'cyyoung111-dev/portfolio',fetchImpl:async()=>({ok:true,json:async()=>({total_count:0,artifacts:[]})}),fetchKr:async(label,symbol)=>{fetched++;return {...row,label,symbol};},fetchPrior:async(label,symbol)=>({label,symbol,date:'2026-10-29',value:200,changePercent:0})};
