import assert from 'node:assert/strict';
import fs from 'node:fs';
import {closeWindow,fetchClosingIndex,prepareClose,deliverClose} from './telegram-close-workflow.mjs';
const date='2026-10-30',now=()=>new Date(date+'T16:30:00+09:00');
assert.equal(closeWindow(new Date(date+'T16:29:59+09:00')).allowed,false);
assert.equal(closeWindow(now()).allowed,true);
