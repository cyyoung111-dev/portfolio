import assert from 'node:assert/strict';
import collector from '../src/web/domain/market/market_briefing_provider_collector.js';
import normalizer from '../src/web/domain/market/market_briefing_provider_normalizer.js';
const request=async(action,params)=>{assert.equal(action,'getBenchmarks');assert.match(params.benchmarks,/KOSPI/);return {series:{KOSPI:[{date:'2026-09-17',value:3400}],KOSDAQ:[{date:'2026-09-17',value:900}],SP500:[{date:'2026-09-17',value:6600}],NASDAQ100:[{date:'2026-09-17',value:24000}]},symbols:{SP500:'^GSPC',NASDAQ100:'^NDX'}};};
const result=await collector.collect(request,'2026-09-18',{from:'2026-09-17'});
assert.deepEqual(result.missing,[]);
assert.equal(result.payload.KOSPI.tradingDate,'2026-09-17');
assert.equal(result.payload.SP500.source,'YAHOO');
assert.equal(result.payload.KOSPI.timestamp,undefined);
const rows=normalizer.normalizeMap(result.payload,{tradingDate:'2026-09-18',receivedAt:'2026-09-18T05:00:00+09:00'});
assert.equal(rows.length,4);
assert.equal(rows.find(x=>x.seriesId==='KOSPI').tradingDate,'2026-09-17');
assert.equal(rows.find(x=>x.seriesId==='KOSPI').timestampQuality,undefined);
assert.equal(rows.find(x=>x.seriesId==='KOSPI').observedAt,null);
assert.equal(rows.find(x=>x.seriesId==='SPX').status,'FINAL');
const partial=normalizer.normalizeOne('VIX',{value:15,tradingDate:'2026-09-17',source:'CBOE'},{receivedAt:'2026-09-18T05:00:00+09:00'});
assert.equal(partial.status,'PARTIAL');
const fx=normalizer.normalizeOne('USDKRW',{value:1380,tradingDate:'2026-09-18',status:'LIVE'},{receivedAt:'2026-09-18T05:00:00+09:00'});
assert.equal(fx.market,'FX');
console.log('기존 GAS provider → 브리핑 collector/normalizer 회귀검사 통과');
