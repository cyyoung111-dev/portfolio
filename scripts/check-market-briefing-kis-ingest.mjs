import assert from 'node:assert/strict';
import wire from '../src/web/domain/market/market_briefing_kis_wire.js';
import adapters from '../src/web/domain/market/market_briefing_adapters.js';
import ingest from '../src/web/domain/market/market_briefing_kis_ingest.js';
const registry={H0MFCNT0:{schemaId:'kis-night-confirmed-v1',fieldCount:3,fields:['SYMB','FUTS_PRPR','ACML_VOL']}};
const raw='0|H0MFCNT0|1|101V09^350.25^1200';
const frame=wire.validateFrame(raw,registry);
assert.equal(frame.status,'VALID');
const decoded=ingest.decodeNamed(frame,registry.H0MFCNT0);
assert.equal(decoded.values.FUTS_PRPR,'350.25');
const result=ingest.k200NightObservation(wire,adapters,raw,registry,{tradingDate:'2026-09-18',receivedAt:'2026-09-18T05:59:59+09:00',observedAt:'2026-09-18T05:59:58+09:00',status:'FINAL',finality:'NIGHT_FINAL'});
assert.equal(result.status,'VALID');
assert.equal(result.observation.seriesId,'K200_NIGHT');
assert.equal(result.observation.value,350.25);
assert.equal(result.observation.session,'NIGHT');
assert.equal(result.observation.status,'FINAL');
const unknown=ingest.k200NightObservation(wire,adapters,'0|H0MFCNT0|1|101V09^350.25^1200',{}, {tradingDate:'2026-09-18',receivedAt:'2026-09-18T06:00:00+09:00'});
assert.equal(unknown.status,'QUARANTINED');
const unnamed={H0MFCNT0:{schemaId:'count-only',fieldCount:3}};
const unnamedResult=ingest.k200NightObservation(wire,adapters,raw,unnamed,{tradingDate:'2026-09-18',receivedAt:'2026-09-18T06:00:00+09:00'});
assert.equal(unnamedResult.status,'QUARANTINED');
assert.equal(unnamedResult.error,'SEMANTIC_SCHEMA_MISSING');
console.log('KIS 검증 스키마 → K200 야간선물 관측 변환 회귀검사 통과');
